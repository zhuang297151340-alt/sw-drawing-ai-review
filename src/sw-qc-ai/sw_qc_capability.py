# ===========================================================================
# 四、取数辅助
# ===========================================================================
def find_capability(part_class, feature, size_mm):
    """
    按 零件类别/特征类型/尺寸 找可达公差。
    返回 (工艺, 可达公差, 类型, 说明) 或 None。
    特征类型用「包含」匹配（图上叫法不同也能命中）。
    """
    best = None
    for (cls, proc, feat, lo, hi, tol, kind, note) in PROCESS_CAPABILITY:
        if cls != part_class:
            continue
        if feat not in feature and feature not in feat:
            continue
        if lo <= size_mm <= hi:
            best = (proc, tol, kind, note, feat, lo, hi)
            break
    return best
