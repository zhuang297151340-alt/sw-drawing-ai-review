def category_of(rule_id, module: str = "") -> str:
    """归档到三大类：先按「一级模块」，再按 rule_id 前缀兜底。"""
    mod = str(module or "").strip()
    if mod in _CAT_BY_MODULE:
        return _CAT_BY_MODULE[mod]
    rid = str(rule_id or "").upper()
    for cat, prefixes in _CAT_RULES:
        for p in prefixes:
            if rid.startswith(p.upper()):
                return cat
    return "图纸信息"



