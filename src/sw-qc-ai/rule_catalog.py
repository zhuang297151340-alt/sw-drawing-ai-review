def _row_dict(r: tuple) -> dict:
    """把一行元组变成 dict，并应用严重级别裁定、补上「待你确认」标记。"""
    d = dict(zip([c[0] for c in COLUMNS], r))
    try:
        d["cat"] = category_of(d.get("id", ""), d.get("module", ""))
    except Exception:
        d["cat"] = ""
    if d["id"] in SEVERITY_POLICY:
        d["sev"] = SEVERITY_POLICY[d["id"]][0]
    # 「待你确认」= 标记 + 一句话说明（空串表示不用管）
    try:
        need = confirmation_needed(d)
        d["confirm"] = (need + " " + confirmation_detail(d)).strip() if need else ""
    except Exception:
        d["confirm"] = ""
    return d


