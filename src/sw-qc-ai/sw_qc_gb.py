def tolerance_grade_consistency(size_tol: str) -> tuple[float, float] | None:
    """
    公差等级 → 经验 Ra 区间（公差越紧，粗糙度要求越高）。
    用于「公差-粗糙度匹配」检查。返回 (Ra_min, Ra_max)。
    """
    if not size_tol:
        return None
    t = size_tol.upper()
    if t.startswith(("IT5", "H5", "h5", "IT6", "H6", "h6", "H7", "h7", "N9", "P9")):
        return (0.2, 0.8)
    if t.startswith(("IT8", "H8", "h8", "IT9", "H9", "h9", "f7", "g6")):
        return (0.8, 3.2)
    if t.startswith(("IT10", "IT11", "H11", "h11")):
        return (1.6, 6.3)
    if t.startswith(("IT12", "IT13", "IT14")):
        return (6.3, 12.5)
    return None


