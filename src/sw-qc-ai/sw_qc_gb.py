def thread_pitch_required(diameter: float, pitch: float | None) -> tuple[bool, str]:
    """
    判断某个螺纹规格是否**必须**写出螺距。

    返回 (是否必须标螺距, 说明)。THD-002 的判据：
      • 图上没写螺距，且该直径**有粗牙** → 可以不写（粗牙默认），不必报
      • 图上没写螺距，但该直径**没有粗牙** → 必须写，报漏标
      • 写了螺距 → 再校验它是否落在该直径的细牙系列里（写错要报）
    """
    d = float(diameter)
    if pitch is None:
        if d in M_NO_COARSE_DIAMETERS:
            return True, f"M{d:g} 无粗牙规格，必须标注螺距"
        if d in M_COARSE_PITCH:
            return False, f"M{d:g} 可省略螺距（粗牙 P={M_COARSE_PITCH[d]:g}）"
        return False, f"M{d:g} 不在 GB/T 193 常用系列内，无法判定"
    allowed = M_FINE_PITCHES.get(d) or []
    coarse = M_COARSE_PITCH.get(d)
    if coarse is not None and abs(pitch - coarse) < 1e-9:
        return False, f"P={pitch:g} 即 M{d:g} 粗牙"
    if allowed and not any(abs(pitch - p) < 1e-9 for p in allowed):
        return True, (f"P={pitch:g} 不在 M{d:g} 的标准螺距系列内"
                      f"（可选 {'/'.join(f'{p:g}' for p in allowed)}）")
    return False, ""


