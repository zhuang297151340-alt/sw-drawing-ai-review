def _apply_spec_overrides() -> str:
    """
    把核对回导的数据套到基表上。返回一行状态说明（供导出脚本打印）。

    只覆盖出现过的键：**工程师没动过的表保持代码基线**，
    这样"只核对了两张表"也不会把其余表意外清空。
    """
    import json
    import os as _os

    path = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), _OVERRIDE_FILE)
    # 自检与"看纯基线"的场景要能跳过覆盖层：
    #   QC_SPEC_NO_OVERRIDE=1 python export_spec_library.py
    # 没有这个开关，回导自检会拿"已覆盖的值"去比，永远零差异 —— 假通过。
    if _os.environ.get("QC_SPEC_NO_OVERRIDE"):
        return "规格库覆盖：已按 QC_SPEC_NO_OVERRIDE 跳过（按代码基线）"
    if not _os.path.isfile(path):
        return ""
    try:
        # utf-8-sig：手工用记事本编辑过的 JSON 常带 BOM，
        # 用 utf-8 读会直接 JSONDecodeError 导致整份覆盖被忽略 —— 太冤。
        with open(path, "r", encoding="utf-8-sig") as fh:
            data = json.load(fh)
    except Exception as exc:                      # 损坏不致命
        return f"规格库覆盖文件损坏，已忽略：{exc!r}"

    applied: list[str] = []

    def _copy_values(target: dict, incoming: dict, label: str) -> None:
        """按 等级/部位 → 值列表 覆盖，长度不符则跳过并记录（不猜）。"""
        for key, values in (incoming or {}).items():
            if key not in target:
                applied.append(f"{label}『{key}』不在基线表中，已跳过")
                continue
            cur = target[key]
            base = cur["values"] if isinstance(cur, dict) and "values" in cur else None
            if base is not None and len(values) != len(base):
                applied.append(f"{label}『{key}』段数不符（表 {len(values)} / 代码 {len(base)}），已跳过")
                continue
            if base is not None:
                cur["values"] = list(values)
            else:
                target[key] = list(values)

    _copy_values(GB_T_1800_IT, data.get("it"), "IT")
    _copy_values(GB_T_1804_LINEAR, data.get("linear"), "线性公差")
    _copy_values(GB_T_1804_ANGLE, data.get("angle"), "角度公差")
    _copy_values(GB_T_1804_RADIUS, data.get("radius"), "倒圆倒角")

    for kind, grades in (data.get("geom") or {}).items():
        table = GB_T_1184.get(kind)
        if table is None:
            applied.append(f"几何公差『{kind}』不在基线表中，已跳过")
            continue
        for grade in ("H", "K", "L"):
            if grade in grades:
                values = list(grades[grade])
                if len(values) != len(table["bounds"]):
                    applied.append(f"几何公差『{kind}/{grade}』段数不符，已跳过")
                    continue
                table[grade] = values

    if data.get("ra_series"):
        GB_T_131_RA_SERIES[:] = [float(v) for v in data["ra_series"]]

    # 表面处理表的核对批注（人写的话），覆盖式合并
    remarks = data.get("surface_remarks") or {}
    if remarks:
        SURFACE_TREATMENT_REMARKS.clear()
        SURFACE_TREATMENT_REMARKS.update(
            {str(k): str(v) for k, v in remarks.items() if str(v).strip()})

    SPEC_OVERRIDES.update(data)
    if not applied:
        return "规格库覆盖：已套用核对回导值"
    return "规格库覆盖：" + "；".join(applied)


