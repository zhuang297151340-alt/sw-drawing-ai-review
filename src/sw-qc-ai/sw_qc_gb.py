def _fund_bucket(size: float) -> int | None:
    """基本偏差表的尺寸段下标（0~12，仅 ≤500mm）。"""
    s = abs(float(size))
    if s <= 0:
        return None
    for i, upper in enumerate(_FUND_BOUNDS):
        if s <= upper:
            return i
    return None


def fundamental_deviation(code: str, size: float) -> dict | None:
    """
    查基本偏差（单位 µm）。

    code 如 'h6' / 'k6' / 'H7' / 'P7'（大小写敏感：大写=孔，小写=轴）。
    返回：
        {"kind": "es"/"ei"/"ES"/"EI", "value": µm, "confidence": ..., "legacy": 旧版值或None}
    超出表范围（>500mm 或缺数据）返回 None —— **不猜**。
    """
    m = re.match(r"^([A-Za-z]{1,2})\s*(\d{1,2})$", (code or "").strip())
    if not m:
        return None
    letters, grade = m.group(1), int(m.group(2))
    idx = _fund_bucket(size)
    if idx is None:
        return None

    if letters.isupper():                      # 孔
        entry = HOLE_FUNDAMENTAL_DEVIATION.get(letters)
        if not entry:
            return None
        if entry.get("verified") is False:
            # 该档位等级归属存疑，**不参与检查**（宁可不查，不报错的）
            return None
        val = entry["values"][idx]
        if val is None:
            return None
        kind = entry["kind"]
        # 2026-10-25 修：K/M/N（等级 ≤IT8）与 P~ZC（等级 ≤IT7）要加 Δ 换算，
        # Δ = IT(n) − IT(n−1)，**现算**（原来的手工 _DELTA_UM 表是错的）。
        # 2026-10-25 按 GB/T 1800.2 完整实现 Δ 换算：
        #   K/M/N 等级 ≤IT8：ES = 表值 + Δ；>IT8：表值即 EI（不换算）
        #   P~ZC  等级 ≤IT7：ES = 表值 + Δ；>IT7：ES = 表值
        #   Δ = IT(n) − IT(n−1)
        if letters in ("K", "M", "N"):
            if grade <= 8:
                try:
                    itn = it_tolerance(size, "IT%d" % grade)
                    itn1 = it_tolerance(size, "IT%d" % (grade - 1))
                    if itn is not None and itn1 is not None:
                        val = val + (itn - itn1)
                except Exception:
                    pass
            else:
                kind = "EI"          # 等级 >IT8：表值是下偏差
        elif letters in ("P", "R", "S"):
            if grade <= 7:
                try:
                    itn = it_tolerance(size, "IT%d" % grade)
                    itn1 = it_tolerance(size, "IT%d" % (grade - 1))
                    if itn is not None and itn1 is not None:
                        val = val + (itn - itn1)
                except Exception:
                    pass
        return {"kind": kind, "value": val,
                "confidence": entry.get("confidence", "medium"), "legacy": None}

    entry = SHAFT_FUNDAMENTAL_DEVIATION.get(letters)   # 轴
    if not entry:
        return None
    val = entry["values"][idx] if idx < len(entry["values"]) else None
    if val is None:
        return None
    legacy = None
    lg = LEGACY_1999_SHAFT_LIMITS.get(f"{letters}{grade}")
    if lg and idx < len(lg):
        legacy = lg[idx]
    return {"kind": entry["kind"], "value": val,
            "confidence": entry.get("confidence", "medium"), "legacy": legacy}


def limit_deviation(code: str, size: float) -> tuple[float, float] | None:
    """
    给出该公差带的极限偏差 (下偏差, 上偏差)，单位 µm —— GB/T 1800.2 口径。

    φ30k6 → (1, 14) 即 +0.014/+0.001 mm（现行 2020 版）。
    """
    fd = fundamental_deviation(code, size)
    if fd is None:
        return None
    it = it_tolerance(size, code)
    if it is None:
        return None
    v, kind = fd["value"], fd["kind"]
    if kind in ("es", "ES"):          # 给的是上偏差 → 下偏差 = 上 − IT
        return (v - it, v)
    return (v, v + it)               # 给的是下偏差 → 上偏差 = 下 + IT


