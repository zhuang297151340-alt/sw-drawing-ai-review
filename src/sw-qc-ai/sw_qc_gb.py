# 配合代号里出现的标准公差等级（优先数系）
PREFERRED_GRADES = ["IT5", "IT6", "IT7", "IT8", "IT9", "IT10", "IT11", "IT12"]


def it_tolerance(nominal: float, grade: str) -> int | None:
    """
    GB/T 1800.1 标准公差数值，单位 μm。
    grade 可写 'IT7' 或 '7' 或 'H7'（只取数字）。
    """
    m = re.search(r"(\d{1,2})", str(grade))
    if not m:
        return None
    key = f"IT{int(m.group(1))}"
    table = GB_T_1800_IT.get(key)
    if not table:
        return None
    size = abs(float(nominal))
    for i, upper in enumerate(_IT_BOUNDS):
        if size <= upper:
            return table[i]
    return None


def it_grade_of(nominal: float, tolerance_um: float) -> str | None:
    """反查：给定尺寸与公差值（μm），它对应哪个标准公差等级（允许 2% 误差）。"""
    for grade in PREFERRED_GRADES:
        v = it_tolerance(nominal, grade)
        if v and abs(v - tolerance_um) <= max(0.02 * v, 0.5):
            return grade
    return None


# 常用配合代号的基本偏差方向（只列最常用的，其余只报公差值不判方向）
FIT_DIRECTION = {
    "H": ("lower", 0.0),     # 孔 H：下偏差 0，上偏差 +IT
    "h": ("upper", 0.0),     # 轴 h：上偏差 0，下偏差 -IT
}


def fit_interval(nominal: float, code: str) -> tuple[float, float] | None:
    """
    给出配合代号的标准偏差区间 (下偏差, 上偏差)，单位 μm。

    支持：
      • H7 —— 基孔制孔：下偏差 0，上偏差 +IT
      • h6 —— 基轴制轴：上偏差 0，下偏差 −IT
      • JS7 / js6 —— 对称偏差 ±IT/2
      • 其它字母（f/g/k/m/n/p/r/s…）方向要查基本偏差表，本函数不判断，返回 None
    """
    m = re.match(r"^([A-Za-z]{1,2})\s*(\d{1,2})$", (code or "").strip())
    if not m:
        return None
    letters, digits = m.group(1), m.group(2)
    it = it_tolerance(nominal, digits)
    if it is None:
        return None
    if letters == "H":                       # 大小写敏感：H 是孔，h 是轴
        return (0.0, float(it))
    if letters == "h":
        return (float(-it), 0.0)
    if letters.upper() == "JS":
        return (-it / 2.0, it / 2.0)
    return None


