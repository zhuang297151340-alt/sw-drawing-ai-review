def form_tolerance_series(item: str, main_param: float, grade: int) -> float | None:
    """
    查 GB/T 1184-1996 附录 B 数系表，返回几何公差值（**μm**）。

    item  —— 直线度 / 平面度 / 圆度 / 圆柱度 / 平行度 / 垂直度 / 倾斜度 /
             同轴度 / 对称度 / 圆跳动 / 全跳动
    grade —— 几何公差等级（**不是 IT 等级**）：B2 为 0~12，其余为 1~12
    查不到返回 None（不猜）。
    """
    key = GB_T_1184_ITEM_TABLE.get(str(item or "").strip())
    if not key:
        return None
    tbl = GB_T_1184_SERIES[key]
    if grade not in tbl["grades"]:
        return None
    size = abs(float(main_param))
    for upper, vals in tbl["segments"]:
        if size <= upper:
            return float(vals[grade - tbl["grades"][0]])
    return None


def form_tolerance_grade_of(item: str, main_param: float, value_um: float,
                            tol_ratio: float = 0.0) -> int | None:
    """
    反查：图上注出的几何公差值（μm）对应哪个标准等级。
    找不到（即不是标准数系值）返回 None —— 这本身就是一个有用的检查结果。
    """
    for grade in GB_T_1184_SERIES.get(GB_T_1184_ITEM_TABLE.get(item, ""),
                                      {}).get("grades", []):
        v = form_tolerance_series(item, main_param, grade)
        if v is None:
            continue
        if abs(v - value_um) <= max(tol_ratio * v, 1e-9):
            return grade
    return None

